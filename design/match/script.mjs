// The demo match: an original 4v4 between two invented teams, Azure and Ember, in four rounds.
// Everything visible in the generated footage, events.vtt and the scoreboard comes from this one table,
// so the timeline markers land exactly on what happens on screen.

export const DURATION = 162; // seconds
export const TEAMS = ['Azure', 'Ember'];

// Units: Player 1 leads Azure (POV angle 1), Player 2 leads Ember (POV angle 2).
export const UNITS = [
  { id: 'a1', team: 0, name: 'Player 1' },
  { id: 'a2', team: 0, name: 'Azure 2' },
  { id: 'a3', team: 0, name: 'Azure 3' },
  { id: 'a4', team: 0, name: 'Azure 4' },
  { id: 'e1', team: 1, name: 'Player 2' },
  { id: 'e2', team: 1, name: 'Ember 2' },
  { id: 'e3', team: 1, name: 'Ember 3' },
  { id: 'e4', team: 1, name: 'Ember 4' },
];

// Rounds: start time, end time, winner, and how it was won.
export const ROUNDS = [
  { n: 1, start: 0.5, end: 31, winner: 0, by: 'objective', capture: 28 },
  { n: 2, start: 40, end: 71, winner: 1, by: 'objective', capture: 68 },
  { n: 3, start: 80, end: 121, winner: 0, by: 'elimination' },
  { n: 4, start: 130, end: 158, winner: 0, by: 'objective', capture: 155 },
];

// Eliminations: time, shooter, target. The clutch is Player 1 alone against three.
export const KILLS = [
  { t: 11, by: 'a1', on: 'e3' },
  { t: 17, by: 'e1', on: 'a2' },
  { t: 22.5, by: 'a3', on: 'e4' },
  { t: 49, by: 'e1', on: 'a1' },
  { t: 55.5, by: 'e4', on: 'a3' },
  { t: 61, by: 'a4', on: 'e2' },
  { t: 88, by: 'a1', on: 'e2' },
  { t: 97, by: 'e1', on: 'a2' },
  { t: 99.5, by: 'e3', on: 'a3' },
  { t: 102, by: 'e4', on: 'a4' },
  { t: 109, by: 'a1', on: 'e1', clutch: 1 },
  { t: 113.5, by: 'a1', on: 'e3', clutch: 2 },
  { t: 118, by: 'a1', on: 'e4', clutch: 3 },
  { t: 139, by: 'e1', on: 'a4' },
  { t: 145, by: 'a1', on: 'e3' },
  { t: 150, by: 'a2', on: 'e2' },
];

const unit = (id) => UNITS.find((u) => u.id === id);

/** events.vtt: round starts, eliminations, objectives and the clutch, as kind|label cues. */
export function eventsVtt() {
  const cue = (t, text) => {
    const f = (s) => {
      const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = (s % 60).toFixed(3).padStart(6, '0');
      return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${sec}`;
    };
    return { t, text: `${f(t)} --> ${f(t + 1)}\n${text}` };
  };
  const cues = [];
  for (const r of ROUNDS) {
    if (r.n > 1) cues.push(cue(r.start, `round|Round ${r.n} starts`));
    if (r.capture) cues.push(cue(r.capture, `obj|Objective captured · ${TEAMS[r.winner]}|${'ab'[r.winner]}`));
  }
  for (const k of KILLS) {
    if (k.clutch === 3) cues.push(cue(k.t, `clutch|Clutch · 1v3 · ${unit(k.by).name}|${'ab'[unit(k.by).team]}`));
    else if (!k.clutch || k.clutch === 1) cues.push(cue(k.t, `elim|Elimination · ${unit(k.by).name} → ${unit(k.on).name}|${'ab'[unit(k.by).team]}`));
  }
  cues.sort((a, b) => a.t - b.t);
  return `WEBVTT\n\nNOTE\nEvents for the Vantage demo match, generated by design/match/script.mjs.\nCue text is kind|label|team: elim, clutch, obj or round; team is a or b (the side that scored), optional.\n\n${cues.map((c) => c.text).join('\n\n')}\n`;
}

/** Scoreboard rows for match.json: the round and score at each moment it changes. */
export function scoreboard() {
  const rows = [];
  let a = 0, e = 0;
  for (const r of ROUNDS) {
    rows.push({ t: r.start === 0.5 ? 0 : r.start, round: r.n, azure: a, ember: e });
    if (r.winner === 0) a++; else e++;
    rows.push({ t: r.end, round: r.n, azure: a, ember: e });
  }
  return rows;
}
