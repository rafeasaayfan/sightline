// Draws the Vantage icon set and writes it to src/video/icons.ts.
//
//   node design/icons/generate.mjs
//
// One set on a 20px grid with 2px padding. Solid geometry: transport glyphs are filled shapes; line glyphs use a
// 2px stroke with butt caps and miter joins on whole or half pixels, so every edge renders crisp at 20px.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const n = (v) => String(Math.round(v * 100) / 100);
const fill = (d, extra = '') => `<path d="${d}" fill="currentColor"${extra}/>`;
const line = (d) =>
  `<path d="${d}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="butt" stroke-linejoin="miter"/>`;
const svg = (body, size = 20) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}" aria-hidden="true" focusable="false">${body}</svg>`;

/** A six-tooth cog as one filled outline with a round hole. */
function cog(cx, cy, outer, root, hole, teeth = 6, topHalf = 13, rootHalf = 21) {
  const rad = (d) => (d * Math.PI) / 180;
  const at = (r, d) => `${n(cx + r * Math.cos(rad(d)))} ${n(cy + r * Math.sin(rad(d)))}`;
  let d = '';
  for (let k = 0; k < teeth; k++) {
    const c = -90 + (k * 360) / teeth;
    d += `${k ? 'L' : 'M'}${at(root, c - rootHalf)}L${at(outer, c - topHalf)}A${outer} ${outer} 0 0 1 ${at(outer, c + topHalf)}L${at(root, c + rootHalf)}A${root} ${root} 0 0 1 ${at(root, c + 360 / teeth - rootHalf)}`;
  }
  d += `ZM${n(cx + hole)} ${n(cy)}A${hole} ${hole} 0 1 0 ${n(cx - hole)} ${n(cy)}A${hole} ${hole} 0 1 0 ${n(cx + hole)} ${n(cy)}Z`;
  return fill(d, ' fill-rule="evenodd"');
}

const speaker = fill('M3 7.5h3l4.5-3.5v12L6 12.5H3Z');

const icons = {
  play: svg(fill('M6 3.5 16.5 10 6 16.5Z')),
  pause: svg(fill('M5 4h3.5v12H5ZM11.5 4H15v12h-3.5Z')),
  restart: svg(line('M4.5 10a5.5 5.5 0 1 0 1.6-3.9') + fill('M3 3.5v5h5Z')),
  'highlight-prev': svg(fill('M16 4.5v11L8.5 10Z') + fill('M4 4.5h2.5v11H4Z')),
  'highlight-next': svg(fill('M4 4.5v11l7.5-5.5Z') + fill('M13.5 4.5H16v11h-2.5Z')),
  'volume-high': svg(speaker + line('M13 7.5a3.5 3.5 0 0 1 0 5M15 5a7 7 0 0 1 0 10')),
  'volume-low': svg(speaker + line('M13 7.5a3.5 3.5 0 0 1 0 5')),
  'volume-off': svg(speaker + line('M12.5 7.5l5 5M17.5 7.5l-5 5')),
  'captions-on': svg(fill('M3 4h14a1 1 0 0 1 1 1v10a1 1 0 0 1-1 1H3a1 1 0 0 1-1-1V5a1 1 0 0 1 1-1ZM5 7.5h4v1.75h-2.25v1.5H9v1.75h-4ZM11 7.5h4v1.75h-2.25v1.5H15v1.75h-4Z', ' fill-rule="evenodd"')),
  'captions-off': svg(line('M3 5h14v10H3Z') + fill('M5 7.5h4v1.75h-2.25v1.5H9v1.75h-4ZM11 7.5h4v1.75h-2.25v1.5H15v1.75h-4Z')),
  gear: svg(cog(10, 10, 8, 6, 2.5)),
  'pip-enter': svg(line('M17 9V5H3v10h5') + fill('M10 11h8v6h-8Z')),
  'pip-exit': svg(line('M17 9V5H3v10h5') + line('M11 12l5 4M11 12v3.5M11 12h3.5')),
  'fullscreen-enter': svg(line('M3 8V3h5M12 3h5v5M17 12v5h-5M8 17H3v-5')),
  'fullscreen-exit': svg(line('M8 3v5H3M17 8h-5V3M12 17v-5h5M3 12h5v5')),
  chevron: svg(line('M7.5 5l5 5-5 5')),
  keyboard: svg(line('M2 5h16v10H2Z') + fill('M5 8h2v2H5ZM9 8h2v2H9ZM13 8h2v2h-2ZM6 11.5h8v1.5H6Z')),
  /** Centre play: a solid glyph drawn on its own 24px grid. */
  'play-large': svg(fill('M8 5 19.5 12 8 19Z'), 24),
};

const body = Object.entries(icons)
  .map(([name, markup]) => `  '${name}':\n    '${markup}',`)
  .join('\n');
const out = `// Generated by design/icons/generate.mjs. Edit the generator, not this file.\n\n/** The Vantage icon set, registered under the \`vantage\` family. */\nexport const vantageIcons: Record<string, string> = {\n${body}\n};\n`;

const target = fileURLToPath(new URL('../../src/video/icons.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${Object.keys(icons).length} icons to ${target}`);
